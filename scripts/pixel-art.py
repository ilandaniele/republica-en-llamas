"""Pixel-art asset pipeline for images generated outside the repo (e.g. with Codex).

Usage (from repo root):
    uvx --with pillow python scripts/pixel-art.py prompts          # rewrite art/PROMPTS.md from art/prompts.json
    uvx --with pillow python scripts/pixel-art.py import [ids...]  # pixelate art/raw/<id>.png into the web app

Import downsamples each raw image to its group grid, quantizes it to a small palette,
scales it back up with nearest neighbour, writes apps/web/public/illustrations/<id>.webp
and points apps/web/src/assets/image-manifest.json at the local file.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "art" / "prompts.json"
PROMPTS_MD = ROOT / "art" / "PROMPTS.md"
RAW_DIR = ROOT / "art" / "raw"
OUT_DIR = ROOT / "apps" / "web" / "public" / "illustrations"
MANIFEST = ROOT / "apps" / "web" / "src" / "assets" / "image-manifest.json"
PALETTE_COLORS = 32
UPSCALE = 4
ID_PREFIX = {"presidents": "portrait_", "characters": "char_"}


def build_assets(config: dict) -> dict[str, dict]:
    assets = {}
    for group_name, group in config["groups"].items():
        moods = group.get("moods", {"": ""})
        for subject_id, subject in group["assets"].items():
            for mood, expression in moods.items():
                asset_id = ID_PREFIX.get(group_name, "") + subject_id + (f"_{mood}" if mood else "")
                parts = [config["style"], group["framing"], subject, expression]
                assets[asset_id] = {
                    "group": group_name,
                    "size": group["size"],
                    "grid": group["grid"],
                    "prompt": " ".join(part[0].upper() + part[1:].rstrip(".") + "." for part in parts if part),
                }
    return assets


def write_prompts(assets: dict[str, dict]) -> None:
    lines = [
        "# Pixel-art prompts",
        "",
        "Generated by `scripts/pixel-art.py prompts` from `art/prompts.json`. Do not edit by hand.",
        "",
        f"{len(assets)} images. Save each one as `art/raw/<id>.png` at the size shown.",
        "",
    ]
    current_group = None
    for asset_id, asset in assets.items():
        if asset["group"] != current_group:
            current_group = asset["group"]
            lines += [f"## {current_group}", ""]
        lines += [f"### {asset_id}", "", f"Size: {asset['size']}", "", "```text", asset["prompt"], "```", ""]
    PROMPTS_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {PROMPTS_MD.relative_to(ROOT)} ({len(assets)} prompts)")


def pixelate(source: Path, target: Path, grid: list[int]) -> None:
    from PIL import Image

    image = Image.open(source).convert("RGB")
    small = image.resize(tuple(grid), Image.Resampling.BOX)
    small = small.quantize(colors=PALETTE_COLORS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    big = small.convert("RGB").resize((grid[0] * UPSCALE, grid[1] * UPSCALE), Image.Resampling.NEAREST)
    big.save(target, "WEBP", lossless=True)


def import_assets(assets: dict[str, dict], selected: list[str]) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for asset_id in selected or list(assets):
        source = RAW_DIR / f"{asset_id}.png"
        if not source.exists():
            print("missing", asset_id)
            continue
        pixelate(source, OUT_DIR / f"{asset_id}.webp", assets[asset_id]["grid"])
        manifest[asset_id] = f"/illustrations/{asset_id}.webp"
        print("ok", asset_id)
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> None:
    command, *ids = sys.argv[1:] or ["prompts"]
    assets = build_assets(json.loads(CONFIG.read_text(encoding="utf-8")))
    if command == "prompts":
        write_prompts(assets)
    elif command == "import":
        unknown = [asset_id for asset_id in ids if asset_id not in assets]
        if unknown:
            sys.exit(f"unknown ids: {', '.join(unknown)}")
        import_assets(assets, ids)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
