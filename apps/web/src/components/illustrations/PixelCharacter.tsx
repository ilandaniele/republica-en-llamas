// ─── Component ────────────────────────────────────────────────────────────────
interface PixelCharacterProps {
  id: string;
  size?: number;
  mood?: Mood;
}

export function PixelCharacter({ id, size = 128, mood = 'normal' }: PixelCharacterProps) {
  const spriteSet = SPRITES[id];
  if (!spriteSet) return null;

  const { palette, sprites } = spriteSet;
  const rows = sprites[mood] ?? sprites['normal']!;
  const GRID = 32;
  const CELL = 4; // 4px per "pixel" in viewBox space

  const rects: React.ReactElement[] = [];
  for (let y = 0; y < Math.min(rows.length, GRID); y++) {
    const row = rows[y] ?? '';
    for (let x = 0; x < Math.min(row.length, GRID); x++) {
      const key = row[x] ?? '0';
      if (key === '0') continue;
      const color = palette[key];
      if (!color || color === 'transparent') continue;
      rects.push(
        <rect key={`${x}-${y}`} x={x * CELL} y={y * CELL} width={CELL} height={CELL} fill={color} />
      );
    }
  }

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${GRID * CELL} ${GRID * CELL}`}
      xmlns="http://www.w3.org/2000/svg"
      style={{ imageRendering: 'pixelated' }}
      shapeRendering="crispEdges"
    >
      {rects}
    </svg>
  );
}
